import { fireEvent, render, screen, waitFor } from "@testing-library/react";
import { afterEach, expect, it, vi } from "vitest";
import { DesktopShell } from "../../src/desktop/DesktopShell";
import { connectWindow, isDesktop } from "../../src/desktop/window";
import { registerCloseGuard } from "../../src/desktop/closeGuard";
import { Workspace } from "../../src/ui/Workspace";
import type { NotesStore } from "../../src/domain/contracts";
vi.mock("../../src/desktop/window", () => ({ isDesktop: vi.fn(), connectWindow: vi.fn() }));
afterEach(() => { vi.restoreAllMocks(); vi.unstubAllGlobals(); });
it("peeks the rail and navigates Settings with guarded history", async () => {
  localStorage.clear();
  vi.stubGlobal("matchMedia", () => ({ matches: true, addEventListener: vi.fn(), removeEventListener: vi.fn() }));
  vi.mocked(isDesktop).mockReturnValue(true);
  vi.mocked(connectWindow).mockResolvedValue({ minimize: vi.fn(async () => {}), toggleMaximize: vi.fn(async () => {}), isMaximized: async () => false, close: vi.fn(async () => {}), startDragging: vi.fn(async () => {}), showSystemMenu: vi.fn(async () => {}), finishClose: vi.fn(async () => {}), dispose: vi.fn() });
  const mutation = vi.fn(async () => { throw new Error("Unexpected write"); });
  const store: NotesStore = { list: async () => [], get: async () => null, create: mutation, update: mutation, trash: mutation, restore: mutation, erase: mutation, subscribe: () => () => {}, persistence: () => ({ status: "ready" }), close: vi.fn() };
  render(<DesktopShell><Workspace store={store} session={{ accountId: "synthetic", deviceId: "synthetic", email: "test@example.invalid", deviceState: "trusted" }} onSignOut={async () => {}} /></DesktopShell>);
  const sidebar = await screen.findByLabelText("Notes navigation");
  fireEvent.click(screen.getByRole("button", { name: "Hide sidebar" }));
  expect(sidebar).toHaveAttribute("data-expanded", "false");
  expect(sidebar).toHaveAttribute("data-pinned", "false");
  fireEvent.pointerEnter(sidebar, { pointerType: "mouse" });
  expect(sidebar).toHaveAttribute("data-expanded", "true");
  expect(sidebar).toHaveAttribute("data-pinned", "false");
  fireEvent.pointerLeave(sidebar, { pointerType: "mouse" });
  expect(sidebar).toHaveAttribute("data-expanded", "false");
  expect(screen.getByLabelText("Notes navigation")).toBe(sidebar);
  fireEvent.click(screen.getByRole("button", { name: "App menu" }));
  fireEvent.click(screen.getByRole("menuitem", { name: "Settings" }));
  await screen.findByRole("region", { name: "Settings screen" });
  expect(screen.queryByRole("dialog", { name: "Settings" })).not.toBeInTheDocument();
  const back = screen.getByRole("button", { name: "Back" });
  await waitFor(() => expect(back).toBeEnabled());
  const release = registerCloseGuard(() => false);
  fireEvent.click(back);
  expect(screen.getByRole("region", { name: "Settings screen" })).toBeInTheDocument();
  release();
  fireEvent.click(back);
  await waitFor(() => expect(screen.queryByRole("region", { name: "Settings screen" })).not.toBeInTheDocument());
  fireEvent.click(screen.getByRole("button", { name: "Forward" }));
  expect(await screen.findByRole("region", { name: "Settings screen" })).toBeInTheDocument();
});
